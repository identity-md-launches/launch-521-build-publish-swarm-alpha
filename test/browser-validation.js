async (page) => {
  const base = page.url().split('#')[0];
  const checks = [];
  const failures = [];
  const assert = (condition, name, detail) => { if (!condition) { failures.push({name,detail}); throw new Error(name + ': ' + JSON.stringify(detail)); } checks.push(name); };
  await page.goto(base);
  await page.locator('.project-card').first().waitFor();
  assert(await page.locator('#project-search').inputValue() === '', 'Search starts empty');
  assert(await page.locator('.project-card').count() === 9, 'Project pagination starts with nine cards');
  const search = page.getByRole('searchbox', {name:'Find your next discovery'});
  for (const query of ['pepe2pepe','pepe2pepe.fun','https://pepe2pepe.fun/','HTTPS://WWW.PEPE2PEPE.FUN/','#1974','NFT #1974','51361']) {
    await search.fill(query);
    assert(await page.locator('.project-card h3').filter({hasText:'Pepe2Pepe'}).count() === 1, 'Search: '+query);
  }
  const contracts = await page.evaluate(async () => (await (await fetch('./data/featured.json')).json()).find(p=>p.id==='pepe2pepe').contracts);
  await search.fill(contracts[0].address.toUpperCase());
  assert(await page.locator('.project-card h3').filter({hasText:'Pepe2Pepe'}).count() === 1, 'Case-insensitive contract search');
  await search.fill('a-project-that-does-not-exist-000');
  assert(await page.getByRole('heading',{name:'No projects match your search'}).isVisible(),'Empty search gives recovery action');
  await page.getByRole('button',{name:'Clear search and filters'}).click();
  await page.getByRole('combobox',{name:'Category',exact:true}).selectOption('Finance');
  assert(await page.locator('.project-card').count()>0,'Category filter returns projects');
  assert((await page.locator('.project-card .card-tags').allTextContents()).every(t=>t.includes('Finance')),'Category filter respects every visible card');
  await page.getByRole('combobox',{name:'Category',exact:true}).selectOption('All categories');
  await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('Publication failed');
  assert(await page.locator('.project-card').count()===3,'Failed publication records retained');
  await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('All statuses');
  await page.getByRole('combobox',{name:'Sort by',exact:true}).selectOption('Name A–Z');
  const names=await page.locator('.project-card h3').allTextContents();
  assert(names.every((n,i)=>!i||names[i-1].localeCompare(n)<=0),'Alphabetical sorting');
  await page.getByRole('button',{name:'Next projects page',exact:true}).click();
  assert((await page.getByRole('navigation',{name:'Projects pagination',exact:true}).innerText()).includes('Page 2'),'Project pagination advances');
  await page.getByRole('button',{name:'Previous projects page',exact:true}).click();
  await page.getByRole('combobox',{name:'Sort by',exact:true}).selectOption('Featured first');
  await page.getByRole('button',{name:'Switch to dark theme'}).click();
  await page.reload();await page.locator('.project-card').first().waitFor();
  assert(await page.evaluate(()=>document.documentElement.dataset.theme)==='dark','Dark theme survives reload');
  await page.getByRole('button',{name:'Switch to light theme'}).click();
  await page.getByRole('link',{name:'Project details for Pepe2Pepe'}).click();
  assert(await page.getByRole('heading',{name:'Pepe2Pepe',exact:true}).isVisible(),'Hash detail navigation');
  assert(await page.getByText('Platform attribution still pending').isVisible(),'Unknown platform attribution prominent');
  assert((await page.locator('#builders').innerText()).includes('Marketing video builder'),'Marketing attribution separated from platform builder');
  await page.getByRole('link',{name:'Contracts',exact:true}).click();
  await page.waitForFunction(()=>document.activeElement.id==='contracts');
  assert(await page.evaluate(()=>document.activeElement.id)==='contracts','Detail navigation focuses section');
  const networkText=await page.locator('#contracts').innerText();
  assert(networkText.includes('Ethereum')&&networkText.includes('Robinhood'),'Featured network labels preserved');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  const copy=page.locator('#contracts button').first();await copy.click();await page.waitForFunction(()=>document.querySelector('#contracts button')?.textContent.includes('Copied'));
  assert((await copy.innerText()).includes('Copied'),'Contract copy button reports success');
  assert((await page.evaluate(()=>navigator.clipboard.readText())).startsWith('0x'),'Contract copy puts address on clipboard');
  assert(await page.locator('#timeline .timeline-summary').count()===0,'No invented elapsed time for external project');
  await page.getByRole('link',{name:'Site directory',exact:true}).click();
  await page.waitForFunction(()=>document.activeElement.id==='directory');
  assert(await page.evaluate(()=>document.activeElement.id)==='directory','Site directory navigation focuses section');
  assert((await page.locator('.count-label').innerText()).includes('151 records + 2 user submissions'),'Registry records distinguished from external submissions');
  await page.getByRole('combobox',{name:'Record type',exact:true}).selectOption('Old version');
  assert(await page.locator('.directory-row').count()===9,'All nine old-version records available');
  await page.getByRole('combobox',{name:'Record type',exact:true}).selectOption('User submission');
  assert(await page.locator('.directory-row').count()===2,'Two external user submissions labeled');
  await page.getByRole('searchbox',{name:'Search site records'}).fill('pepe2pepe.fun');
  assert(await page.locator('.directory-row').count()===1,'Bottom directory URL search');
  await page.getByRole('searchbox',{name:'Search site records'}).fill('');
  await page.getByRole('combobox',{name:'Record type',exact:true}).selectOption('All records');
  await page.getByRole('button',{name:'Next directory page',exact:true}).click();
  assert((await page.getByRole('navigation',{name:'Directory pagination'}).innerText()).includes('Page 2'),'Site directory pagination advances');
  await page.goto(base+'#/project/%broken');
  assert(await page.getByRole('heading',{name:'Project not found'}).isVisible(),'Malformed route recovers without crashing');
  await page.goto('about:blank');await page.goto(base);await page.locator('.project-card').first().waitFor();
  await page.keyboard.press('Tab');
  assert((await page.evaluate(()=>document.activeElement.textContent)).includes('Skip to content'),'Keyboard begins with skip link');
  await page.keyboard.press('Enter');
  assert(await page.evaluate(()=>document.activeElement.id)==='main','Keyboard skip reaches main');
  for(const width of [1440,834,390,320]){
    await page.setViewportSize({width,height:900});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No home horizontal overflow at '+width);
    await page.goto(base+'#/project/pepe2pepe');await page.locator('#contracts').waitFor();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No detail horizontal overflow at '+width);
    await page.goto(base+'#/');await page.locator('.project-card').first().waitFor();
  }
  await page.setViewportSize({width:1440,height:1100});
  await page.getByText('Live refresh unavailable.',{exact:false}).waitFor();
  assert(await page.locator('.project-card').count()===9,'Real CORS failure keeps complete snapshot visible');
  return {passed:checks.length, checks, failures};
}
